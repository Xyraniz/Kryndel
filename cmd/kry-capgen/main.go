	if err != nil {
		fail(err)
	}
	directELF, err := stringCases("machine_dynamic.go", "emitExpr")
	if err != nil {
		fail(err)
	}
	// Print calls are lowered by emitStatements/emitStaticOutput rather than
	// directMachine.emitExpr's builtin switch.
	directELF = append(directELF, "print", "println")
	sort.Strings(directELF)
	interpreter, err := stringCases("runtime.go", "evalBuiltin")
	if err != nil {
		fail(err)
	}
	selfHosted, err := selfHostedBuiltinNames("../../selfhost/source_kir_compiler.kry", "builtin.go")
	if err != nil {
		fail(err)
	}
	languageTypes, err := typeIdentifiers("types.go", "TypeKind", "Ty")
	if err != nil {
		fail(err)
	}
	languageTypes = filterNames(languageTypes, map[string]bool{"TyError": true, "TyUnknown": true})
	languageExprKinds, err := typeIdentifiers("ast.go", "ExprKind", "Ex")
	if err != nil {
		fail(err)
	}
	languageStmtKinds, err := typeIdentifiers("ast.go", "StmtKind", "St")
	if err != nil {
		fail(err)
	}
	languagePatternKinds, err := typeIdentifiers("ast.go", "PatternKind", "Pat")
	if err != nil {
		fail(err)
	}
	languageUnaryOperators, err := grammarOperatorCases("parser.go", "unary", "match")
	if err != nil {
		fail(err)
	}
	languageBinaryOperators, err := identifierCases("parser.go", "precedence", "k", "@OP")
	if err != nil {
		fail(err)
	}
	selfHostedKinds, err := selfHostedKindInventories("../../selfhost/source_kir_compiler.kry")
	if err != nil {
		fail(err)
	}
	caseInventories := []struct {
		name, file, function, selector, prefix string
	}{
		{"generatedCAOTExprKinds", "codegen.go", "expr", "Kind", "Ex"},
		{"generatedCAOTStmtKinds", "codegen.go", "stmt", "Kind", "St"},
		{"generatedCAOTPatternKinds", "codegen.go", "patternCond", "Kind", "Pat"},
		{"generatedCAOTUnaryOperators", "codegen.go", "unary", "Op", "@OP"},
		{"generatedCAOTBinaryOperators", "codegen.go", "binary", "Op", "@OP"},
		{"generatedInterpreterExprKinds", "runtime.go", "evalExpr", "Kind", "Ex"},
		{"generatedInterpreterStmtKinds", "runtime.go", "execStmt", "Kind", "St"},
		{"generatedInterpreterPatternKinds", "runtime.go", "matchPattern", "Kind", "Pat"},
		{"generatedInterpreterUnaryOperators", "runtime.go", "evalExpr", "Op", "@OP"},
		{"generatedInterpreterBinaryOperators", "runtime.go", "evalBinary", "Op", "@OP"},
		{"generatedDirectELFExprKinds", "machine_dynamic.go", "emitExpr", "Kind", "Ex"},
		{"generatedDirectELFStmtKinds", "machine_dynamic.go", "emitStatements", "Kind", "St"},
		{"generatedDirectELFUnaryOperators", "machine_dynamic.go", "emitExpr", "Op", "@OP"},
		{"generatedDirectELFBinaryOperators", "machine_dynamic.go", "emitBinary", "Op", "@OP"},
		{"generatedDirectELFTypes", "machine_dynamic.go", "machineValueTypeSupported", "Kind", "Ty"},
	}
	generatedCases := make(map[string][]string, len(caseInventories))
	for _, inventory := range caseInventories {
		values, err := identifierCases(inventory.file, inventory.function, inventory.selector, inventory.prefix)
		if err != nil {
			fail(err)
		}
		generatedCases[inventory.name] = values
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&out, "package kry")
	fmt.Fprintln(&out, "var generatedCAOTBuiltinCases = map[string]struct{}{")
	writeCases(&out, cAOT)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedDirectELFBuiltinCases = map[string]struct{}{")
	writeCases(&out, directELF)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedInterpreterBuiltinCases = map[string]struct{}{")
	writeCases(&out, interpreter)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedSelfHostedBuiltinNames = map[string]struct{}{")
	writeCases(&out, selfHosted)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedLanguageTypeKinds = map[string]struct{}{")
	writeCases(&out, languageTypes)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedLanguageExprKinds = map[string]struct{}{")
	writeCases(&out, languageExprKinds)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedLanguageStmtKinds = map[string]struct{}{")
	writeCases(&out, languageStmtKinds)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedLanguagePatternKinds = map[string]struct{}{")
	writeCases(&out, languagePatternKinds)
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "var generatedLanguageUnaryOperators = map[string]struct{}{")
